import { createFileRoute } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { useServerFn } from "@tanstack/react-start";
import { Lock } from "lucide-react";
import { ResearchShell } from "@/components/layout/ResearchShell";
import { ErrorState, LoadingState } from "@/components/common/States";
import { getRandomisationConfig } from "@/lib/randomisation-config.functions";

export const Route = createFileRoute("/_authenticated/research/randomisation-configuration")({
  head: () => ({
    meta: [
      { title: "Randomisation Configuration — NeuroCare Connect" },
      { name: "description", content: "Read-only view of the study's fixed allocation method and ratio." },
      { property: "og:title", content: "Randomisation Configuration — NeuroCare Connect" },
      { property: "og:description", content: "The study's fixed, read-only randomisation settings." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: RandomisationConfiguration,
});

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="grid gap-1 border-b border-border/60 py-3 last:border-0 sm:grid-cols-[14rem_1fr]">
      <dt className="text-sm font-semibold text-muted-foreground">{label}</dt>
      <dd className="text-sm text-foreground">{value}</dd>
    </div>
  );
}

function RandomisationConfiguration() {
  const fetchConfig = useServerFn(getRandomisationConfig);
  const { data, isPending, error, refetch } = useQuery({
    queryKey: ["randomisation-config"],
    queryFn: () => fetchConfig(),
  });

  return (
    <ResearchShell
      title="Randomisation Configuration"
      description="The allocation settings used for this study. Read-only."
      breadcrumbs={[{ label: "Research" }, { label: "Randomisation Configuration" }]}
    >
      {isPending ? (
        <LoadingState label="Loading configuration" />
      ) : error ? (
        <ErrorState description={error.message} onRetry={() => void refetch()} />
      ) : (
        <section className="frost space-y-4 rounded-3xl p-6">
          <p className="flex items-center gap-2 text-sm font-semibold text-brand-deep">
            <Lock aria-hidden="true" className="size-4" />
            Fixed in the current implementation — not editable through this page
          </p>
          <dl>
            <Row label="Allocation method" value={data.method} />
            <Row label="Allocation ratio" value={data.ratio} />
            <Row label="Study groups" value={data.groups.join(" and ")} />
            <Row
              label="Individual assignment"
              value="Generated by the application. Researchers cannot choose a participant's group during normal randomisation."
            />
            <Row
              label="Prerequisites"
              value="Eligibility, consent, enrolment and baseline must be complete before allocation."
            />
            <Row label="Configuration type" value="Fixed; not editable" />
            <Row
              label="Method recorded on allocations"
              value={
                data.recordedMethods.length
                  ? `${data.recordedMethods.join("; ")} (${data.allocatedCount} allocation${data.allocatedCount === 1 ? "" : "s"})`
                  : "No allocations recorded yet"
              }
            />
          </dl>
          <p className="text-xs text-muted-foreground">
            Block randomisation and stratification are not part of the approved configuration. Corrections to an individual
            allocation are handled separately in Randomisation Control, which needs extra permission.
          </p>
        </section>
      )}
    </ResearchShell>
  );
}
