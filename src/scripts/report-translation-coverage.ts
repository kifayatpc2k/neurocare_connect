// Writes docs/translation-coverage.md from the real catalogues.
// Run after build-patient-catalogs: bun scripts/report-translation-coverage.ts
import { readFileSync, writeFileSync } from "node:fs";
import { walkStrings } from "../src/i18n/localize";
import { patientContentSources } from "../src/i18n/content-sources";
import { patientUi } from "../src/i18n/patient-ui";
import { helpL10n } from "../src/i18n/patient-help";

const langs = ["hi", "kn", "mr", "ur"] as const;
const en: string[] = JSON.parse(readFileSync("src/i18n/catalog/en.json", "utf8"));
const cat = Object.fromEntries(langs.map((l) => [l, JSON.parse(readFileSync(`src/i18n/catalog/${l}.json`, "utf8")) as Record<string, string>]));

const labels: Record<string, string> = {
  articles: "Library articles (all sections, takeaways)", catalogue: "Medicine catalogue (20 records, categories, disclaimer)",
  checklist: "Appointment checklist (16 items, prompts, notices)", seekHelp: "When to seek medical help (full page content)",
  faqs: "Library FAQs", libraryGlossary: "Library glossary terms", glossary: "Study glossary terms", learningChecks: "Learning checks",
  leaflets: "Printable leaflets", libraryIntro: "Library introduction", librarySections: "Library sections",
  education: "Patient home page content", chat: "Ask NeuroCare answers", journeyStages: "Study pathway steps", glossaryTitle: "Glossary title",
};
const domainOf = new Map<string, string>();
const rows: [string, number, Record<string, number>][] = [];
for (const [k, v] of Object.entries(patientContentSources)) {
  const set = new Set<string>(); walkStrings(v, (s) => set.add(s));
  set.forEach((s) => domainOf.has(s) || domainOf.set(s, k));
  rows.push([labels[k] ?? k, set.size, Object.fromEntries(langs.map((l) => [l, [...set].filter((s) => cat[l]![s]).length]))]);
}
const ui = en.filter((s) => !domainOf.has(s));
rows.push(["Interface text in components (buttons, labels, captions, print text)", ui.length, Object.fromEntries(langs.map((l) => [l, ui.filter((s) => cat[l]![s]).length]))]);
const keys = Object.keys(patientUi.en).length;
rows.push(["Shared header/notice strings", keys, Object.fromEntries(langs.map((l) => [l, Object.values(patientUi[l]).filter(Boolean).length]))]);
rows.push(["Emergency (112) panel and warning signs", helpL10n.en.emergencyGroups.flatMap((g) => g.items).length, Object.fromEntries(langs.map((l) => [l, helpL10n[l].emergencyGroups.flatMap((g) => g.items).length]))]);

const cell = (n: number, t: number) => (n === t ? `${n}/${t} ✓` : `${n}/${t}`);
let md = `# Patient-area translation coverage\n\nGenerated by \`scripts/report-translation-coverage.ts\` from the real catalogues — do not edit by hand.\n\n`;
md += `Languages: English (source), हिन्दी Hindi, ಕನ್ನಡ Kannada, मराठी Marathi, اُردُو Urdu (right to left).\n\n`;
md += `**Review status for every non-English string: draft translation — awaiting linguistic review and clinical review. Nothing is approved.**\n\n`;
md += `| Content | Strings | Hindi | Kannada | Marathi | Urdu |\n|---|---|---|---|---|---|\n`;
for (const [name, total, by] of rows) md += `| ${name} | ${total} | ${langs.map((l) => cell(by[l]!, total)).join(" | ")} |\n`;
md += `| **All catalogue strings** | ${en.length} | ${langs.map((l) => cell(en.length - Number(cat[l]!["__missing"]), en.length)).join(" | ")} |\n\n`;
md += `## Intentionally kept in English\n\n- Medicine names, generic names and abbreviations (NRS, DN4, NePIQoL, DRP, PCNE), so they match prescriptions and study forms.\n- Source titles, publishers and URLs, so readers can find the original page.\n- Medicine search keywords (English); patients can also search translated summaries and uses.\n- The separate public Study page (/study) and Study team page are outside the patient area and are not translated.\n- Ask NeuroCare understands questions typed in English or by tapping a suggested question; typed questions in other languages fall back to the general answer.\n\n`;
md += `## Missing strings\n\n`;
for (const l of langs) {
  const miss = en.filter((s) => !cat[l]![s]);
  md += `- ${l}: ${miss.length ? miss.length + " missing — shown in English with a page notice" : "none"}\n`;
}
writeFileSync("docs/translation-coverage.md", md);
console.log("written");
